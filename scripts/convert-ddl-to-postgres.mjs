import fs from "node:fs/promises";

const source = await fs.readFile("migration/source-ddl.sql", "utf8");
const blocks = source.match(/CREATE TABLE[\s\S]*?\) ENGINE=[^;]+;/g) ?? [];
const tableNames = new Set();
const createStatements = [];
const indexes = [];
const foreignKeys = [];

for (const block of blocks) {
  const tableMatch = block.match(/CREATE TABLE `([^`]+)`/);
  if (!tableMatch) continue;
  const tableName = tableMatch[1];
  tableNames.add(tableName);
  const body = block
    .replace(/^CREATE TABLE `[^`]+` \(/, "")
    .replace(/\) ENGINE=[^;]+;$/, "")
    .split("\n")
    .map(line => line.trim().replace(/,$/, ""))
    .filter(Boolean);
  const columns = [];
  const constraints = [];
  for (const raw of body) {
    if (raw.startsWith("PRIMARY KEY")) {
      const key = raw.match(/PRIMARY KEY \((.*)\)/)?.[1];
      if (key) constraints.push(`PRIMARY KEY (${key})`);
      continue;
    }
    const unique = raw.match(/^UNIQUE KEY `([^`]+)` \((.*)\)$/);
    if (unique) {
      constraints.push(`CONSTRAINT "${unique[1]}" UNIQUE (${unique[2]})`);
      continue;
    }
    const key = raw.match(/^KEY `([^`]+)` \((.*)\)$/);
    if (key) {
      indexes.push(`CREATE INDEX IF NOT EXISTS "${key[1]}" ON "${tableName}" (${key[2].replaceAll("`", '"')});`);
      continue;
    }
    const fk = raw.match(/^CONSTRAINT `([^`]+)` FOREIGN KEY \(([^)]+)\) REFERENCES `([^`]+)` \(([^)]+)\)(.*)$/);
    if (fk) {
      foreignKeys.push(`ALTER TABLE "${tableName}" ADD CONSTRAINT "${fk[1]}" FOREIGN KEY (${fk[2].replaceAll("`", '"')}) REFERENCES "${fk[3]}" (${fk[4].replaceAll("`", '"')}) ON DELETE NO ACTION ON UPDATE NO ACTION;`);
      continue;
    }
    columns.push(raw);
  }
  let converted = [...columns, ...constraints].join(",\n  ");
  converted = converted
    .replaceAll("`", '"')
    .replace(/int NOT NULL AUTO_INCREMENT/g, "integer GENERATED BY DEFAULT AS IDENTITY NOT NULL")
    .replace(/int AUTO_INCREMENT/g, "integer GENERATED BY DEFAULT AS IDENTITY")
    .replace(/int NOT NULL/g, "integer NOT NULL")
    .replace(/int DEFAULT/g, "integer DEFAULT")
    .replace(/ int$/g, " integer")
    .replace(/tinyint\(1\) NOT NULL DEFAULT '0'/g, "boolean NOT NULL DEFAULT false")
    .replace(/tinyint\(1\) NOT NULL DEFAULT '1'/g, "boolean NOT NULL DEFAULT true")
    .replace(/tinyint\(1\)/g, "boolean")
    .replace(/double/g, "double precision")
    .replace(/enum\([^)]*\)/g, "text")
    .replace(/ COLLATE utf8mb4_unicode_ci/g, "")
    .replace(/ DEFAULT '0'/g, " DEFAULT 0")
    .replace(/ DEFAULT '1'/g, " DEFAULT 1")
    .replace(/ DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP/g, " DEFAULT CURRENT_TIMESTAMP")
    .replace(/ DEFAULT CURRENT_TIMESTAMP/g, " DEFAULT CURRENT_TIMESTAMP");
  createStatements.push(`CREATE TABLE IF NOT EXISTS "${tableName}" (\n  ${converted}\n);`);
}

const sql = [
  "BEGIN;",
  ...createStatements,
  ...indexes,
  ...foreignKeys,
  "COMMIT;",
  "",
].join("\n\n");
await fs.writeFile("migration/postgres-schema.sql", sql, "utf8");
console.log(JSON.stringify({ tables: tableNames.size, createStatements: createStatements.length, indexes: indexes.length, foreignKeys: foreignKeys.length, bytes: sql.length }, null, 2));
